export function getNearestExpedition(list: readonly Expedition[] = expeditions): Expedition | undefined {
  const now = Date.now();
  const upcoming = list
    .filter(e => e.timer?.enabled && e.timer.targetDate)
    .map(e => ({ e, ts: new Date(e.timer!.targetDate).getTime() }))
    .filter(({ ts }) => ts >= now)
    .sort((a, b) => a.ts - b.ts);

  return upcoming[0]?.e;
}